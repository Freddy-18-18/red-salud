/**
 * Combina sugerencias del catálogo con motivos frecuentes del doctor.
 * Los frecuentes van PRIMERO (mayor relevancia). Dedupe case-insensitive
 * preservando la capitalización del primero que aparezca.
 */
export function mergeReasonSuggestions(
  frequentReasons: ReadonlyArray<string>,
  catalog: ReadonlyArray<string> = REASON_CATALOG,
): string[] {
  const seen = new Set<string>();
  const result: string[] = [];

  for (const r of frequentReasons) {
    const key = r.trim().toLowerCase();
    if (key.length === 0 || seen.has(key)) continue;
    seen.add(key);
    result.push(r.trim());
  }

  for (const r of catalog) {
    const key = r.trim().toLowerCase();
    if (key.length === 0 || seen.has(key)) continue;
    seen.add(key);
    result.push(r.trim());
  }

  return result;
}

/**
 * Devuelve los top-N motivos como "quick chips" para mostrar arriba del
 * textarea — click rápido sin abrir dropdown. Prioriza los frecuentes del
 * doctor (más relevantes), rellena con los más útiles del catálogo.
 */
export function getQuickReasonChips(
  frequentReasons: ReadonlyArray<string>,
  maxChips: number = 6,
): string[] {
  return mergeReasonSuggestions(frequentReasons).slice(0, maxChips);
}
